/* ---------------------------------------------------------
   TINY MARKDOWN RENDERER (headers, --- dividers, **bold**)
--------------------------------------------------------- */
function inlineBold(text, keyPrefix) {
  const parts = text.split(/(\*\*[^*]+\*\*)/g);
  return parts.map((part, i) => {
    if (part.startsWith("**") && part.endsWith("**")) {
      return (
        <strong key={`${keyPrefix}-${i}`} style={{ color: T.goldText, fontWeight: 600 }}>
          {part.slice(2, -2)}
        </strong>
      );
    }
    return <React.Fragment key={`${keyPrefix}-${i}`}>{part}</React.Fragment>;
  });
}

function MarkdownLite({ text }) {
  const lines = text.split("\n");
  const blocks = [];
  let para = [];

  const flushPara = (key) => {
    if (para.length) {
      blocks.push(
        <p className="reading-paragraph" key={`p-${key}`} style={{ margin: "0 0 14px 0", lineHeight: 1.75, color: T.ivoryText, fontSize: 16 }}>
          {inlineBold(para.join(" "), `p-${key}`)}
        </p>
      );
      para = [];
    }
  };

  lines.forEach((raw, idx) => {
    const line = raw.trim();
    if (line === "") {
      flushPara(idx);
      return;
    }
    if (line === "---") {
      flushPara(idx);
      blocks.push(
        <div
          key={`hr-${idx}`}
          style={{ height: 1, margin: "28px 0", background: `linear-gradient(90deg, transparent, ${T.goldSoft}, transparent)` }}
        />
      );
      return;
    }
    if (line.startsWith("# ")) {
      flushPara(idx);
      blocks.push(
        <h2
          className="reading-heading"
          key={`h-${idx}`}
          style={{
            fontFamily: displayFont,
            fontSize: 26,
            fontWeight: 600,
            color: T.ink,
            margin: "6px 0 14px 0",
            letterSpacing: 0.2,
          }}
        >
          {line.slice(2)}
        </h2>
      );
      return;
    }
    para.push(line);
  });
  flushPara("end");

  return <div>{blocks}</div>;
}

