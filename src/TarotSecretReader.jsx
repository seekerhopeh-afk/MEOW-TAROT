function intentCardPrecision(card, interpretation={}, position=1) {
  const intent = interpretation?.intent;
  const profile = INTENT_SIGNAL_PROFILE[intent];
  if (!profile) return { text:"", score:0, positiveHits:0, cautionHits:0 };
  const tags = cardTags(card);
  const positiveHits = profile.positive.reduce((n,t)=>n+(tags.has(t)?1:0),0);
  const cautionHits = profile.caution.reduce((n,t)=>n+(tags.has(t)?1:0),0);
  const positionWeight = [0.8,1.0,1.35][position] || 1;
  let score = (positiveHits - cautionHits) * positionWeight;
  if (card.reversed) score -= 0.45 * positionWeight;
  const exact = INTENT_CARD_OVERRIDES[card.sub]?.[intent] || INTENT_CARD_OVERRIDES[card.name]?.[intent] || "";
  let text = exact;
  if (!text && (positiveHits || cautionHits)) {
    if (positiveHits > cautionHits) text = `เมื่ออ่านเจาะไปที่เจตนา “${intent}” ใบนี้ช่วยหนุนประเด็น${profile.focus}`;
    else if (cautionHits > positiveHits) text = `เมื่ออ่านเจาะไปที่เจตนา “${intent}” ใบนี้ทำให้ต้องระวังเรื่อง${profile.focus}`;
    else text = `เมื่ออ่านเจาะไปที่เจตนา “${intent}” ใบนี้ให้ทั้งแรงสนับสนุนและเงื่อนไขในประเด็น${profile.focus}`;
  }
  return { text, score, positiveHits, cautionHits };
}

