  insight += ".";

  if (interpretation.intent === "THIRD_PARTY") {
    insight += " อย่างไรก็ดี สัญญาณเรื่องความลับหรือความไม่ชัดยังไม่ใช่หลักฐานยืนยันว่ามีบุคคลที่สาม";
  }
