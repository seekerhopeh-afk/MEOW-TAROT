function parseMinor(card) {
  const m = card.sub.match(/^(Ace|Two|Three|Four|Five|Six|Seven|Eight|Nine|Ten|Page|Knight|Queen|King) of (Wands|Cups|Swords|Pentacles)$/);
  return m ? { rank:m[1], suit:m[2] } : null;
}

function cardTags(card) {
  const tags = new Set();
  const minor = parseMinor(card);
  if (card.sub === "Major Arcana") {
    const map = {
      "The Fool":["new","movement"], "The Magician":["agency","action"], "The High Priestess":["hidden","pause"],
      "The Empress":["growth","support"], "The Emperor":["structure","control"], "The Hierophant":["structure","commitment"],
      "The Lovers":["choice","connection"], "The Chariot":["movement","action"], Strength:["resilience","control"],
      "The Hermit":["distance","pause"], "Wheel of Fortune":["change","movement"], Justice:["clarity","facts"],
      "The Hanged Man":["pause","delay"], Death:["ending","change"], Temperance:["balance","healing"],
      "The Devil":["attachment","risk"], "The Tower":["disruption","change"], "The Star":["hope","healing"],
      "The Moon":["hidden","unclear"], "The Sun":["clarity","success"], Judgement:["decision","return"], "The World":["completion","success"]
    };
    (map[card.name]||[]).forEach(x=>tags.add(x));
  } else if (minor) {
    (MINOR_DEEP_TAGS[card.sub] || []).forEach(x=>tags.add(x));
    const suitTags={Wands:["action"],Cups:["emotion","connection"],Swords:["thought"],Pentacles:["practical"]};
    suitTags[minor.suit].forEach(x=>tags.add(x));
    const rankTags={Ace:["new"],Two:["choice"],Three:["growth"],Four:["stability"],Five:["conflict"],Six:["movement"],Seven:["assessment"],Eight:["action"],Nine:["near_completion"],Ten:["completion"],Page:["news","new"],Knight:["movement","action"],Queen:["maturity"],King:["control","maturity"]};
    rankTags[minor.rank].forEach(x=>tags.add(x));
    if (card.sub === "Seven of Swords") { tags.add("hidden"); tags.add("strategy"); }
    if (card.sub === "Two of Swords") { tags.add("stalemate"); tags.add("unclear"); }
    if (card.sub === "Eight of Cups") { tags.add("distance"); tags.add("movement"); }
    if (card.sub === "Six of Cups") { tags.add("past"); tags.add("return"); }
    if (card.sub === "Ten of Swords") { tags.add("ending"); }
    if (card.sub === "Three of Swords") { tags.add("hurt"); tags.add("conflict"); }
    if (card.sub === "Ace of Pentacles") { tags.add("opportunity"); }
  }
  if (card.reversed) { tags.add("blocked"); tags.add("review"); }
  return tags;
}



