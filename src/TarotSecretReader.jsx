function probabilityLabel(cards, interpretation) {
  const ev = intentEvidence(cards, interpretation);
  const confidence = spreadConfidence(cards, interpretation);
  if (confidence.level === "LOW" || confidence.contradiction === "HIGH") return "ปานกลาง";
  if (ev.net >= 3) return "สูง";
  if (ev.net <= -2) return "ต่ำ";
  return "ปานกลาง";
}

function symbolicTiming(cards) {
  const [c1,c2,c3] = cards;
  const t2 = cardTags(c2), t3 = cardTags(c3);
  if (t3.has("movement") || t3.has("newStart") || t3.has("news")) return "ค่อนข้างใกล้ — หลังจากมีการติดต่อ การตัดสินใจ หรือสัญญาณขยับที่ชัดขึ้น";
  if (t2.has("delay") || t3.has("delay") || c2.reversed || c3.reversed) return "ยังต้องรอ — มีเงื่อนไขหรือจุดค้างบางอย่างที่ต้องคลี่คลายก่อน";
  return "ไม่ใช่วันที่ตายตัว แต่เป็นช่วงหลังจากสถานการณ์กลางเรื่องเริ่มชัดและมีการลงมือจริง";
}

