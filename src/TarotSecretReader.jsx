function cardContextMeaning(card, interpretation={domain:"OTHER"}, position=1) {
  const domain = interpretation.domain || "OTHER";
  const role = positionRole(interpretation, position);
  const precision = intentCardPrecision(card, interpretation, position);
  const addPrecision = text => `${text}${precision.text ? ` — ${precision.text}` : ""}`;
  if (card.sub === "Major Arcana") {
    const base = (MAJOR_DOMAIN[card.name] && (MAJOR_DOMAIN[card.name][domain] || MAJOR_DOMAIN[card.name].DECISION)) || (MAJOR_LOCAL[card.name]?.[0] || "มีพลังสำคัญต่อเรื่องนี้");
    if (!card.reversed) return addPrecision(`${role}: ${base}`);
    const rev = MAJOR_LOCAL[card.name]?.[1] || "พลังของไพ่ยังติดขัดหรือแสดงออกไม่เต็มที่";
    return addPrecision(`${role}: ${base} แต่สถานะกลับหัวทำให้ต้องอ่านผ่านเงื่อนไขของ ${rev}`);
  }
  const m = parseMinor(card);
  if (!m) return addPrecision(`${role}: ไพ่ใบนี้สะท้อนพลังที่ต้องอ่านร่วมกับคำถามและไพ่ข้างเคียง`);
  const deep = MINOR_DEEP[card.sub];
  if (deep) {
    const base = deep[domain] || deep.OTHER || deep.DECISION;
    return addPrecision(`${role}: ${card.reversed ? `${base} แต่เมื่อกลับหัว น้ำหนักจะไปที่ ${deep.rev}` : base}`);
  }
  const lens = (DOMAIN_LENS[domain] || DOMAIN_LENS.OTHER)[m.suit];
  const rank = RANK_CONTEXT[m.rank];
  return addPrecision(`${role}: เน้น${lens} โดยเป็น${card.reversed ? rank.rev : rank.up}`);
}

function cardLocalMeaning(card) {
  return cardContextMeaning(card, {domain:"OTHER"}, 1);
}

/* ---------------------------------------------------------
   COMBINATION INTELLIGENCE V3.4
   Reads the three cards as a pattern, not as independent meanings.
   It can strengthen, weaken, or redirect the answer evidence.
--------------------------------------------------------- */
function combinationIntelligence(cards, interpretation={}) {
  const [c1,c2,c3] = cards;
  const sets = cards.map(cardTags);
  const has = (i, tag) => sets[i]?.has(tag);
  const any = tag => sets.some(s => s.has(tag));
  const count = tag => sets.reduce((n,s)=>n+(s.has(tag)?1:0),0);
  const notes = [];
  let positiveShift = 0;
  let cautionShift = 0;
  let movementShift = 0;
  let returnShift = 0;
  let endingShift = 0;
  let clarityShift = 0;
  let uncertaintyShift = 0;

  // Ending -> movement/new = a real transition, not merely a negative ending.
  if ((has(0,"ending") || has(0,"distance") || has(0,"disruption")) &&
      (has(1,"movement") || has(1,"change") || has(1,"new")) &&
      (has(2,"success") || has(2,"opportunity") || has(2,"clarity") || has(2,"movement") || has(2,"new"))) {
    positiveShift += 3; movementShift += 2; endingShift += 1;
    notes.push("ชุดไพ่เปลี่ยนแรงของการจบหรือสั่นคลอนให้กลายเป็นการเคลื่อนออกจากรูปแบบเดิม และปลายทางเปิดกว่าเดิม");
  }

  // Pause/block -> movement = delayed opening; movement should not be read as immediate.
  if ((has(0,"pause") || has(0,"blocked") || has(1,"pause") || has(1,"delay") || has(1,"blocked")) &&
      (has(2,"movement") || has(2,"new") || has(2,"news") || has(2,"opportunity"))) {
    positiveShift += 1; cautionShift += 1; movementShift += 1;
    notes.push("ปลายทางมีแรงขยับ แต่ต้องผ่านจุดค้างหรือเงื่อนไขตรงกลางก่อน จึงไม่ใช่ผลที่เกิดทันที");
  }

  // Connection/past -> message/return/connection = reconnection pattern.
  if ((any("past") || any("return")) && count("connection") >= 1 &&
      (has(2,"news") || has(2,"return") || has(2,"connection") || has(2,"emotion"))) {
    positiveShift += 2; returnShift += 2;
    notes.push("ความผูกพันเดิมไม่ได้อยู่แค่ในความทรงจำ แต่มีสัญญาณต่อเนื่องไปสู่การติดต่อหรือการเชื่อมกลับ");
  }

  // Connection -> distance/ending = affection may exist, but direction is withdrawal/closure.
  if ((has(0,"connection") || has(1,"connection")) && (has(2,"distance") || has(2,"ending") || has(2,"blocked"))) {
    cautionShift += 3; endingShift += 2;
    notes.push("แม้ต้นเรื่องยังมีความผูกพัน แต่ไพ่ปลายทางเปลี่ยนน้ำหนักไปทางระยะห่าง การปิดวงจร หรือการไม่เดินหน้าต่อ");
  }

  // Unclear/hidden followed by clarity = uncertainty can resolve.
  if ((has(0,"hidden") || has(0,"unclear") || has(1,"hidden") || has(1,"unclear")) && has(2,"clarity")) {
    positiveShift += 1; clarityShift += 2; uncertaintyShift -= 1;
    notes.push("ความไม่ชัดในช่วงต้นมีแนวโน้มถูกเปิดให้เห็นชัดขึ้น จึงควรให้น้ำหนักกับข้อมูลหรือการเปิดเผยที่เกิดภายหลัง");
  }

  // Clarity -> unclear/hidden at the end = apparent certainty becomes less reliable.
  if ((has(0,"clarity") || has(1,"clarity")) && (has(2,"unclear") || has(2,"hidden") || has(2,"blocked"))) {
    cautionShift += 2; uncertaintyShift += 2;
    notes.push("สิ่งที่ดูชัดในตอนต้นไม่ได้คงความชัดถึงปลายเรื่อง จึงไม่ควรรีบฟันธงจากข้อมูลช่วงแรก");
  }

  // Stability all through = staying/building has more weight than changing.
  if (count("stability") + count("structure") + count("practical") >= 3 && count("movement") + count("change") <= 1) {
    positiveShift += 1;
    notes.push("ไพ่ทั้งชุดให้น้ำหนักกับการสร้างฐาน จัดระบบ และทำสิ่งเดิมให้แข็งแรง มากกว่าการเปลี่ยนแบบรวดเร็ว");
  }

  // Repeated conflict/risk/blocked is a genuine caution cluster.
  if (count("conflict") + count("risk") + count("blocked") + count("disruption") >= 3) {
    cautionShift += 3;
    notes.push("สัญญาณอุปสรรคซ้ำหลายจุดทำให้ต้องลดน้ำหนักคำตอบเชิงบวก และมองเรื่องนี้แบบมีแผนสำรอง");
  }

  // Strong aligned direction: two or more cards repeat the same major movement/success signal.
  if (count("movement") + count("change") >= 3 && (has(2,"movement") || has(2,"change"))) {
    positiveShift += 2; movementShift += 2;
    notes.push("แรงการเปลี่ยนหรือเคลื่อนที่ถูกย้ำตลอดทั้งชุด ทำให้ทิศทางการขยับมีน้ำหนักมากกว่าการอยู่นิ่ง");
  }
  if (count("success") + count("opportunity") + count("growth") >= 3 && !has(2,"blocked")) {
    positiveShift += 2;
    notes.push("ไพ่หลายใบสนับสนุนโอกาส การเติบโต หรือผลลัพธ์เชิงบวกในทิศเดียวกัน จึงเพิ่มความชัดของแนวโน้ม");
  }

  // Major middle card often acts as the mechanism/turning point, but never automatically as key card.
  if (c2?.sub === "Major Arcana") {
    const r12 = relationshipTypeBasic(c1,c2);
    const r23 = relationshipTypeBasic(c2,c3);
    if (r12.type === "turn" || r23.type === "turn" || has(1,"change") || has(1,"decision") || has(1,"disruption")) {
      notes.push(`${c2.name} อยู่ตำแหน่งกลางและทำหน้าที่เป็นจุดเปลี่ยนที่เชื่อมเหตุจากต้นเรื่องไปสู่ผลปลายทาง`);
    }
  }

  // Intent-specific weighting.
  if (interpretation.intent === "JOB_CHANGE" && movementShift > 0) positiveShift += 1;
  if (interpretation.intent === "RETURN" && returnShift > 0) positiveShift += 1;
  if (interpretation.intent === "THIRD_PARTY") {
    // Combination may increase ambiguity but can never turn it into proof of infidelity.
    if (count("hidden") + count("unclear") >= 2) uncertaintyShift += 1;
    positiveShift = Math.min(positiveShift, 1);
  }

  const strength = Math.min(100, 45 + Math.abs(positiveShift-cautionShift)*10 + Math.min(notes.length,3)*8);
  return {
    positiveShift, cautionShift, movementShift, returnShift, endingShift, clarityShift, uncertaintyShift,
    strength, notes,
    summary: notes[0] || "ไพ่ทั้งสามไหลต่อกันตามลำดับโดยไม่มีชุดสัญญาณพิเศษที่เปลี่ยนน้ำหนักคำตอบอย่างมาก",
  };
}



