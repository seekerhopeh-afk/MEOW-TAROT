function stableHash(text="") {
  let h = 2166136261;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function choosePhrase(list, seed, salt=0) {
  if (!list?.length) return "";
  return list[(stableHash(`${seed}|${salt}`)) % list.length];
}

function stripRolePrefix(text="") {
  return text
    .replace(/^[^:：]{1,48}[:：]\s*/, "")
    .replace(/^เน้น/, "เน้น")
    .replace(/\s+/g, " ")
    .trim();
}

function cleanAnswerText(text="") {
  return text
    .replace(/\*\*/g, "")
    .replace(/\bYES\b/g, "มีแนวโน้มใช่")
    .replace(/\bNO\b/g, "มีแนวโน้มไม่")
    .replace(/\bCONDITIONAL\b/g, "มีเงื่อนไข")
    .replace(/\bUNCLEAR\b/g, "ยังไม่ชัด")
    .replace(/\s+/g, " ")
    .trim();
}

