/* ---------------------------------------------------------
   ANSWER INTELLIGENCE ENGINE V3.2
   Converts question intent + the whole 3-card pattern into a direct answer.
   This is deterministic and runs locally; it does not pretend to be an AI model.
--------------------------------------------------------- */
const POSITIVE_TAGS = new Set(["success","opportunity","growth","clarity","connection","return","movement","new","stability","healing","agency","action","support","maturity","completion"]);
const CAUTION_TAGS = new Set(["blocked","ending","risk","conflict","hurt","distance","unclear","pause","delay","stalemate","disruption","attachment"]);

function tagCount(cards, set) {
  let total = 0;
  cards.forEach(c => cardTags(c).forEach(t => { if (set.has(t)) total += 1; }));
  return total;
}



/* ---------------------------------------------------------
   SPREAD CONFIDENCE & CONTRADICTION ENGINE V3.8
   Confidence = how coherently the three cards answer THIS question.
   It is not a probability that a real-world event will occur.
--------------------------------------------------------- */
function spreadConfidence(cards, interpretation={}) {
  const rels = [
    relationshipType(cards[0], cards[1]),
    relationshipType(cards[1], cards[2]),
    relationshipType(cards[0], cards[2]),
  ];
  const combo = combinationIntelligence(cards, interpretation);
  const tags = cards.map(cardTags);
  const ev = intentEvidenceBase(cards, interpretation);
  const supportCount = rels.filter(r=>r.type === "support").length;
  const turnCount = rels.filter(r=>r.type === "turn").length;
  const tensionCount = rels.filter(r=>r.type === "tension").length;
  const flowCount = rels.filter(r=>r.type === "flow").length;

  // Direction card matters most because it carries the answer/outcome role.
  const direction = tags[2] || new Set();
  const directionClear = direction.has("clarity") || direction.has("success") || direction.has("opportunity") || direction.has("return") || direction.has("ending") || direction.has("movement") || direction.has("stability");
  const directionUnclear = direction.has("unclear") || direction.has("hidden") || direction.has("blocked") || direction.has("stalemate");

  // Semantic agreement: compare positive/caution evidence rather than upright/reversed counts.
  const cardLean = cards.map((card,i)=>{
    const t = tags[i];
    let score = 0;
    t.forEach(x=>{ if (POSITIVE_TAGS.has(x)) score += 1; if (CAUTION_TAGS.has(x)) score -= 1; });
    score += intentCardPrecision(card, interpretation, i).score;
    return score > 0.75 ? 1 : score < -0.75 ? -1 : 0;
  });
  const nonNeutral = cardLean.filter(x=>x!==0);
  const alignedLean = nonNeutral.length >= 2 && Math.abs(nonNeutral.reduce((a,b)=>a+b,0)) === nonNeutral.length;
  const splitLean = nonNeutral.includes(1) && nonNeutral.includes(-1);

  let score = 52;
  score += supportCount * 10;
  score += flowCount * 3;
  score += turnCount * 4; // a coherent turn can still be a clear story
  score -= tensionCount * 13;
  if (alignedLean) score += 12;
  if (splitLean) score -= 14;
  if (directionClear) score += 8;
  if (directionUnclear) score -= 12;
  if (combo.notes.length >= 1) score += 5;
  if (combo.notes.length >= 2) score += 3;
  if (combo.uncertaintyShift > 0) score -= combo.uncertaintyShift * 7;
  if (Math.abs(ev.net) >= 5) score += 7;
  else if (Math.abs(ev.net) <= 1) score -= 7;

  // Third-party/private-thought questions have a hard ceiling because tarot cannot verify facts.
  if (interpretation.intent === "THIRD_PARTY") score = Math.min(score, 58);
  if (interpretation.intent === "FEELINGS") score = Math.min(score, 72);

  score = Math.max(20, Math.min(95, Math.round(score)));
  const level = score >= 75 ? "HIGH" : score >= 48 ? "MEDIUM" : "LOW";

  let contradiction = "LOW";
  if (tensionCount >= 2 || (splitLean && directionUnclear)) contradiction = "HIGH";
  else if (tensionCount === 1 || splitLean || combo.uncertaintyShift > 0) contradiction = "MEDIUM";

  const reasons = [];
  if (alignedLean) reasons.push("ไพ่ส่วนใหญ่เอนไปในทิศเดียวกัน");
  if (supportCount) reasons.push(`มีคู่ไพ่ที่สนับสนุนกัน ${supportCount} คู่`);
  if (turnCount) reasons.push(`มีจุดเปลี่ยนที่อ่านต่อเป็นเหตุผลได้ ${turnCount} จุด`);
  if (tensionCount) reasons.push(`มีแรงขัดกัน ${tensionCount} คู่`);
  if (directionUnclear) reasons.push("ไพ่ปลายทางยังมีความไม่ชัด/ติดเงื่อนไข");
  else if (directionClear) reasons.push("ไพ่ปลายทางให้ทิศทางค่อนข้างชัด");
  if (interpretation.intent === "THIRD_PARTY") reasons.push("คำถามนี้เป็นข้อเท็จจริงเกี่ยวกับบุคคลอื่น จึงไม่ใช้ไพ่ยืนยันข้อกล่าวหา");

  return { score, level, contradiction, supportCount, turnCount, tensionCount, alignedLean, splitLean, reasons, combo };
}

function confidenceThai(c) {
  return c.level === "HIGH" ? "สูง" : c.level === "MEDIUM" ? "ปานกลาง" : "ต่ำ";
}
function contradictionThai(c) {
  return c.contradiction === "HIGH" ? "สูง" : c.contradiction === "MEDIUM" ? "ปานกลาง" : "ต่ำ";
}

function intentEvidenceBase(cards, interpretation) {
  const tags = cards.map(cardTags);
  const has = (i, t) => tags[i]?.has(t);
  let positive = tagCount(cards, POSITIVE_TAGS);
  let caution = tagCount(cards, CAUTION_TAGS) + cards.filter(c=>c.reversed).length;
  let movement = tags.reduce((n,t)=>n+(t.has("movement")||t.has("change")||t.has("new")?1:0),0);
  let stability = tags.reduce((n,t)=>n+(t.has("stability")||t.has("structure")||t.has("control")?1:0),0);
  let clarity = tags.reduce((n,t)=>n+(t.has("clarity")?1:0),0);
  let unclear = tags.reduce((n,t)=>n+(t.has("unclear")||t.has("hidden")||t.has("blocked")?1:0),0);
  let returnSignal = tags.reduce((n,t)=>n+(t.has("return")||t.has("past")||t.has("connection")?1:0),0);
  let ending = tags.reduce((n,t)=>n+(t.has("ending")||t.has("distance")?1:0),0);
  if (has(2,"success") || has(2,"opportunity") || has(2,"clarity") || has(2,"connection") || has(2,"return")) positive += 2;
  if (has(2,"blocked") || has(2,"ending") || has(2,"unclear") || has(2,"conflict")) caution += 2;
  let precisionScore = 0;
  cards.forEach((card, i) => { precisionScore += intentCardPrecision(card, interpretation, i).score; });
  if (precisionScore >= 0.75) positive += Math.min(4, Math.round(precisionScore));
  if (precisionScore <= -0.75) caution += Math.min(4, Math.round(Math.abs(precisionScore)));
  return { positive, caution, movement, stability, clarity, unclear, returnSignal, ending, precisionScore, net: positive-caution };
}
function intentEvidence(cards, interpretation) {
  const tags = cards.map(cardTags);
  const has = (i, t) => tags[i]?.has(t);
  let positive = tagCount(cards, POSITIVE_TAGS);
  let caution = tagCount(cards, CAUTION_TAGS) + cards.filter(c=>c.reversed).length;
  let movement = tags.reduce((n,t)=>n+(t.has("movement")||t.has("change")||t.has("new")?1:0),0);
  let stability = tags.reduce((n,t)=>n+(t.has("stability")||t.has("structure")||t.has("control")?1:0),0);
  let clarity = tags.reduce((n,t)=>n+(t.has("clarity")?1:0),0);
  let unclear = tags.reduce((n,t)=>n+(t.has("unclear")||t.has("hidden")||t.has("blocked")?1:0),0);
  let returnSignal = tags.reduce((n,t)=>n+(t.has("return")||t.has("past")||t.has("connection")?1:0),0);
  let ending = tags.reduce((n,t)=>n+(t.has("ending")||t.has("distance")?1:0),0);

  // The third card describes direction, so give it slightly more weight.
  if (has(2,"success") || has(2,"opportunity") || has(2,"clarity") || has(2,"connection") || has(2,"return")) positive += 2;
  if (has(2,"blocked") || has(2,"ending") || has(2,"unclear") || has(2,"conflict")) caution += 2;

  // V3.7: score every card again through the exact user intent.
  // Position 3 is weighted more because it answers direction/outcome.
  let precisionScore = 0;
  cards.forEach((card, i) => { precisionScore += intentCardPrecision(card, interpretation, i).score; });
  if (precisionScore >= 0.75) positive += Math.min(4, Math.round(precisionScore));
  if (precisionScore <= -0.75) caution += Math.min(4, Math.round(Math.abs(precisionScore)));

  // V3.4: the whole-card combination can amplify, soften, or redirect raw card evidence.
  const combo = combinationIntelligence(cards, interpretation);
  positive += combo.positiveShift;
  caution += combo.cautionShift;
  movement += combo.movementShift;
  returnSignal += combo.returnShift;
  ending += combo.endingShift;
  clarity += combo.clarityShift;
  unclear = Math.max(0, unclear + combo.uncertaintyShift);

  return { positive, caution, movement, stability, clarity, unclear, returnSignal, ending, precisionScore, net: positive - caution, combo };
}

function answerBand(ev, confidence=null) {
  if (confidence?.contradiction === "HIGH" || confidence?.level === "LOW") return "MIXED";
  if (ev.net >= 4) return "POSITIVE";
  if (ev.net <= -3) return "CAUTION";
  return "MIXED";
}

