  const [deck, setDeck] = useState(() => shuffleDeck());
  const [revealed, setRevealed] = useState(() => new Set());
  const [selected, setSelected] = useState([]);
  const [resultText, setResultText] = useState("");
  const [errorMsg, setErrorMsg] = useState("");
  const [shuffling, setShuffling] = useState(false);
  const [popupCard, setPopupCard] = useState(null);
  const [secretCard, setSecretCard] = useState(null);
  const [secretReading, setSecretReading] = useState(null);
  const [secretOpening, setSecretOpening] = useState(false);

  const canProceedForm = question.trim().length > 0;

  const goToDeck = () => {
    if (!canProceedForm) return;
    setStep("deck");
    setShuffling(true);
    setTimeout(() => setShuffling(false), 700);
  };

  const handleCardClick = useCallback((card) => {
    if (selected.length >= 3 || revealed.has(card.id)) return;
    setRevealed((prev) => new Set(prev).add(card.id));
    setSelected((prev) => [...prev, card]);
    setPopupCard(card);
    setTimeout(() => {
      setPopupCard((curr) => (curr && curr.id === card.id ? null : curr));
    }, 3000);
  }, [selected, revealed]);

  const handleRandomPick = useCallback(() => {
    const needed = 3 - selected.length;
    if (needed <= 0) return;
    const pool = deck.filter((c) => !revealed.has(c.id));
    const picks = [];
    const copy = [...pool];
    for (let i = 0; i < needed && copy.length; i++) {
      const idx = Math.floor(Math.random() * copy.length);
      picks.push(copy.splice(idx, 1)[0]);
    }
    picks.forEach((c, i) => {
      setTimeout(() => {
        setRevealed((prev) => new Set(prev).add(c.id));
        setSelected((prev) => [...prev, c]);
        setPopupCard(c);
        setTimeout(() => {
          setPopupCard((curr) => (curr && curr.id === c.id ? null : curr));
        }, 3000);
      }, i * 3200);
    });
  }, [deck, revealed, selected]);

  const reshuffle = () => {
    if (selected.length > 0) return;
    setShuffling(true);
    setTimeout(() => {
      setDeck(shuffleDeck());
      setRevealed(new Set());
      setShuffling(false);
    }, 700);
  };

  const resetAll = () => {
    setStep("form");
    setQuestion("");
    setDesiredInfo("");
    setContext("");
    setDeck(shuffleDeck());
    setRevealed(new Set());
    setSelected([]);
    setResultText("");
    setErrorMsg("");
    setShuffling(false);
    setPopupCard(null);
    setSecretCard(null);
    setSecretReading(null);
    setSecretOpening(false);
  };

